# RFC 3161 id-ct-TSTInfo content-type OID.
_TST_INFO_OID = "1.2.840.113549.1.9.16.1.4"


def _b64u_encode(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode("ascii")


@dataclass
class BuiltBundle:
    """Container for a built test bundle + matching JWKS + signing key.

    The ``tsa_extra_roots_pem`` field carries the PEM-encoded ephemeral
    TSA root generated by the fixture builder. Tests pass this via
    ``ValidateBundleOptions(tsa_extra_trusted_roots_pem=...)`` so the
    real RFC 3161 ``TimeStampResp`` attached to the bundle verifies
    against the test root. The wheel-bundled placeholder root cannot
    sign tokens (no private key in the OSS tree per banned pattern #14),
    so tests must supply their own ephemeral root.
    """

    bundle: dict[str, Any]
    jwks: dict[str, Any]
    signing_key: ed25519.Ed25519PrivateKey
    witness_key: ed25519.Ed25519PrivateKey
    bundle_digest_hex: str
    tsa_extra_roots_pem: bytes = field(default=b"")


def make_keypair(seed: bytes) -> ed25519.Ed25519PrivateKey:
    """Deterministic Ed25519 keypair from a 32-byte seed."""
    if len(seed) != 32:
        raise ValueError(f"seed must be 32 bytes, got {len(seed)}")
    return ed25519.Ed25519PrivateKey.from_private_bytes(seed)


