"""Shared fixtures and helpers for the W10.4 bundle-validator tests.

Provides a small fixture-builder API:

    build_bundle(*, claims, signer_key_id, decided_at, trust_anchor,
                 tsa_token=..., log_inclusion_proof=..., merkle=True)
        -> (bundle_dict, jwks, ...)

The helper creates a deterministic Ed25519 keypair (in-memory; never
written to disk so banned pattern #14 is preserved), signs the canonical
JCS bytes of the bundle payload, builds the Merkle root over claim
digests, and assembles the structured bundle dict.

w9-2 additions:
  * The fixture builder now generates an ephemeral ECDSA P-256 TSA root
    + leaf cert pair AT TEST TIME (private key material lives only in
    process memory) and signs a real RFC 3161 ``TimeStampResp`` over
    the bundle binding digest. The signed DER blob is base64url-encoded
    into the token's ``tsr_der_b64u`` field so the cryptographic
    verifier in ``relay_verifier.tsa.validate_tsa_token`` can decode +
    verify it end-to-end.
  * :class:`BuiltBundle` carries ``tsa_extra_roots_pem`` -- the PEM of
    the ephemeral root -- so each test passes it via
    ``ValidateBundleOptions(tsa_extra_trusted_roots_pem=...)``. The
    real wheel-bundled chain is still consulted; the ephemeral root is
    *additional* trust material for the test.

These helpers are imported by test_w10_4_*.py modules. They are test-
only fixtures and do NOT leak private-key bytes onto disk.

ASCII-only per CLAUDE.md "ASCII-Safe Source".
"""

