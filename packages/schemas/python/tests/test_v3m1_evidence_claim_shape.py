@pytest.mark.plumbing
def test_val_v3m1_015_flat_subject_deprecation_first_occurrence_only() -> None:
    """Deprecation warning emits exactly once per process (per VAL-V3M1-023
    cross-cutting rule reaffirmed in VAL-V3M1-015)."""
    # Reset the process-level emission tracker so the test is hermetic.
    from relay_schemas import envelopes as _env

    _env._FLAT_SUBJECT_DEPRECATION_EMITTED.clear()  # type: ignore[attr-defined]

    ec1 = EvidenceClaim.model_validate(_base_claim())
    ec2 = EvidenceClaim.model_validate(_base_claim())

    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        # Touch flat accessors multiple times across two instances.
        _ = ec1.subject_kind
        _ = ec1.subject_id
        _ = ec2.subject_kind
        _ = ec2.subject_id

    dep_warnings = [
        w for w in caught
        if issubclass(w.category, DeprecationWarning)
        and "subject" in str(w.message).lower()
    ]
    assert len(dep_warnings) == 1, (
        f"VAL-V3M1-015: expected exactly 1 deprecation warning per process; "
        f"got {len(dep_warnings)}"
    )


