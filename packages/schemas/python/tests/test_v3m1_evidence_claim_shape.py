VALID_SHA256 = "sha256-" + ("a" * 64)
VALID_CLAIM_DIGEST = "sha256-" + ("f" * 64)
VALID_MANIFEST_HASH = "sha256-" + ("b" * 64)
VALID_ACTOR_HASH = "sha256-" + ("c" * 64)
VALID_SIGNATURE = "MEUCIQ" + ("D" * 80)


def _new_uuid() -> str:
    return str(uuid.uuid4())


def _base_claim(**overrides: object) -> dict[str, object]:
    """Minimum-valid EvidenceClaim payload using the NEW nested-subject form
    and the 5 new required/optional fields the spec K shape demands.

    The model also accepts the FLAT form (subject_kind/subject_id) via the
    mode='before' shim per VAL-V3M1-015 backward-compatibility contract.
    """
    payload: dict[str, object] = {
        "schema_version": "relay.evidence_claim.v1",
        "evidence_claim_id": _new_uuid(),
        "evidence_bundle_id": _new_uuid(),
        "claim_type": "run_result",
        "subject": {
            "kind": "run",
            "id": _new_uuid(),
            "manifest_commit_hash": VALID_MANIFEST_HASH,
        },
        "evidence_refs": [
            {"kind": "run_result", "ref": "run_results:abc", "digest": VALID_SHA256},
        ],
        "claim_predicate": {
            "op": "and",
            "args": [
                {"op": "run_result_status_is", "value": "accepted"},
            ],
        },
        "claim_digest": VALID_CLAIM_DIGEST,
        "redaction_transform_version": "v1.3",
        "actor_kind": "control_plane",
        "actor_identity_hash": VALID_ACTOR_HASH,
        "occurred_at": "2026-05-12T10:00:05+00:00",
        "manifest_commit_hash": VALID_MANIFEST_HASH,
        "signer_key_id": "kid_2026-05_relay-evidence",
        "signature": VALID_SIGNATURE,
        "supersedes_claim_id": None,
        "namespaces": {"x-relay": {"schema_version": "v1"}},
        "created_at": "2026-05-12T10:00:00+00:00",
    }
    payload.update(overrides)
    return payload


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


