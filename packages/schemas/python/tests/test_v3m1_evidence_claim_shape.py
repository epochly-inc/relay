@pytest.mark.plumbing
def test_val_v3m1_012_pydantic_claim_predicate_field_exists() -> None:
    """claim_predicate is a recursive op/args structure."""
    assert "claim_predicate" in EvidenceClaim.model_fields
    ec = EvidenceClaim.model_validate(_base_claim())
    assert ec.claim_predicate is not None
    assert ec.claim_predicate.op == "and"
    assert len(ec.claim_predicate.args) == 1


@pytest.mark.plumbing
def test_val_v3m1_012_claim_predicate_accepts_depth_8() -> None:
    """A claim_predicate nested exactly 8 levels deep is accepted."""

    def nest(level: int) -> dict[str, object]:
        if level == 0:
            return {"op": "run_result_status_is", "value": "accepted"}
        return {"op": "and", "args": [nest(level - 1)]}

    payload = _base_claim(claim_predicate=nest(7))  # depth: 8 levels of op
    ec = EvidenceClaim.model_validate(payload)
    assert ec.claim_predicate.op == "and"


@pytest.mark.plumbing
def test_val_v3m1_012_claim_predicate_rejects_depth_9() -> None:
    """A claim_predicate nested 9 levels deep is rejected with a structured
    error per VAL-V3M1-012 depth-bound."""

    def nest(level: int) -> dict[str, object]:
        if level == 0:
            return {"op": "run_result_status_is", "value": "accepted"}
        return {"op": "and", "args": [nest(level - 1)]}

    payload = _base_claim(claim_predicate=nest(8))
    with pytest.raises(ValidationError) as excinfo:
        EvidenceClaim.model_validate(payload)
    # The error message should mention depth.
    assert "depth" in str(excinfo.value).lower()


