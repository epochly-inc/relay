@pytest.mark.plumbing
def test_val_v3m1_011_pydantic_evidence_refs_field_exists() -> None:
    """Pydantic EvidenceClaim model declares evidence_refs list field."""
    assert "evidence_refs" in EvidenceClaim.model_fields, (
        "VAL-V3M1-011: evidence_refs missing from Pydantic EvidenceClaim"
    )
    ec = EvidenceClaim.model_validate(_base_claim())
    assert isinstance(ec.evidence_refs, list)
    assert len(ec.evidence_refs) == 1
    ref = ec.evidence_refs[0]
    # EvidenceRef should carry kind/ref and optionally digest/value.
    assert ref.kind == "run_result"
    assert ref.ref == "run_results:abc"
    assert ref.digest == VALID_SHA256


