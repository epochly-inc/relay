@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-004")
def test_udf_coverage_all_three_udfs_present_allowlist_only() -> None:
    """udf_coverage guard (VAL-CWC-P3CORPUS-004): all three allowlist UDFs are
    exercised, and no case references a UDF outside the allowlist."""
    udfs_used = {c["udf"] for c in _cases()}
    assert udfs_used == UDF_ALLOWLIST, (
        "VAL-CWC-P3CORPUS-004: corpus must exercise exactly the 3 allowlist UDFs; "
        f"got {sorted(udfs_used)}"
    )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-004")
def test_cases_drive_through_cel_dotted_form() -> None:
    """Every case drives the UDF THROUGH CEL: the input_expression contains the
    dotted UDF call (not a direct Python callable invocation)."""
    for case in _cases():
        expr = case["input_expression"]
        assert case["udf"] + "(" in expr, (
            f"VAL-CWC-P3CORPUS-004: case {case.get('label')!r} must drive "
            f"{case['udf']} THROUGH CEL (dotted call in input_expression)"
        )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-004")
def test_at_least_one_boundary_case_per_udf() -> None:
    """Each UDF has at least one >=2-key map-literal boundary case that cel-js
    cannot parse (cel_js_parseable == false)."""
    boundary_by_udf: dict[str, int] = {}
    for case in _cases():
        if case["cel_js_parseable"] is False:
            boundary_by_udf[case["udf"]] = boundary_by_udf.get(case["udf"], 0) + 1
    missing = [udf for udf in UDF_ALLOWLIST if boundary_by_udf.get(udf, 0) < 1]
    assert missing == [], (
        "VAL-CWC-P3CORPUS-004: each UDF needs >= 1 cel_js_parseable=false boundary "
        f"case; missing for: {sorted(missing)}"
    )
