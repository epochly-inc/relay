    """Every case carries engines == ["wasm"] exactly (structural cel-js fence)."""
    offenders = [
        c.get("label") for c in _cases() if c.get("engines") != ["wasm"]
    ]
    assert offenders == [], (
        "VAL-CWC-P3CORPUS-001: every case MUST carry engines == ['wasm']; "
        f"offenders: {offenders}"
    )


