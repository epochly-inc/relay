@pytest.mark.fulfills("VAL-CWC-P3CORPUS-001")
def test_udf_via_cel_corpus_shape_separate_file() -> None:
    """The NEW corpus exists, is non-empty, and is a SEPARATE file from
    relay_cel_corpus.json (different path; this runner never reads the legacy
    corpus)."""
    assert CORPUS_PATH.exists(), f"missing {CORPUS_PATH}"
    assert CORPUS_PATH != LEGACY_CORPUS_PATH
    assert LEGACY_CORPUS_PATH.exists(), "legacy corpus must still exist (untouched)"
    cases = _cases()
    assert len(cases) > 0


