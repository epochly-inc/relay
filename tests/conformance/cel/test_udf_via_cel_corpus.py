@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-003")
def test_golden_matches_fresh_wasm_eval() -> None:
    """Each stored golden equals a FRESH wasm eval of the same case through CEL
    (determinism: the built wasm reproduces the recorded golden)."""
    gen = _load_generator()
    cel = gen.RelayCel()
    failures: list[str] = []
    for case in _cases():
        response = gen._wasm_eval(cel, case["input_expression"], case["bindings"])
        fresh_value = response["value"]
        if fresh_value != case["golden_typed"]:
            failures.append(
                f"{case.get('label')!r}: golden={json.dumps(case['golden_typed'], sort_keys=True)} "
                f"fresh={json.dumps(fresh_value, sort_keys=True)}"
            )
        # JCS b64 must also match the fresh recompute.
        from relay_contracts import jcs_canonicalize  # noqa: PLC0415

        fresh_b64 = base64.b64encode(jcs_canonicalize(fresh_value)).decode("ascii")
        if fresh_b64 != case["py_jcs_b64"]:
            failures.append(f"{case.get('label')!r}: py_jcs_b64 drift")
    assert failures == [], (
        "VAL-CWC-P3CORPUS-003: golden != fresh wasm eval:\n  " + "\n  ".join(failures)
    )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-003")
def test_golden_cross_anchors_cel_python_direct_call() -> None:
    """Each case's golden equals the FIXED cel-python DIRECT-call result
    serialized to typed-canonical (the parity that replaces the retired
    two-engine test_w17_4 comparison)."""
    gen = _load_generator()
    from relay_contracts.wasm_codec import py_to_typed  # noqa: PLC0415

    failures: list[str] = []
    for case in _cases():
        direct = gen._apply_direct(case["udf"], case["direct_args"])
        direct_typed = py_to_typed(direct)
        if direct_typed != case["golden_typed"]:
            failures.append(
                f"{case.get('label')!r}: wasm-golden="
                f"{json.dumps(case['golden_typed'], sort_keys=True)} "
                f"cel-py-direct={json.dumps(direct_typed, sort_keys=True)}"
            )
    assert failures == [], (
        "VAL-CWC-P3CORPUS-003: cross-anchor wasm-via-CEL != cel-python-direct:\n  "
        + "\n  ".join(failures)
    )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-003")
def test_generator_check_mode_reports_no_drift() -> None:
    """Re-running the generator in --check mode against the on-disk corpus
    reports no drift (the corpus is byte-deterministic vs a fresh run)."""
    gen = _load_generator()
    corpus = gen.build_corpus()
    serialised = json.dumps(corpus, indent=2, sort_keys=True) + "\n"
    on_disk = CORPUS_PATH.read_text(encoding="utf-8")
    assert serialised == on_disk, (
        "VAL-CWC-P3CORPUS-003: corpus drift -- regenerate via "
        "`uv run python scripts/generate-relay-udf-via-cel-corpus.py`"
    )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-003")
def test_generator_aborts_on_cross_anchor_divergence() -> None:
    """A deliberately-wrong direct-call result makes build_case raise the
    cross-anchor divergence (the abort path is real, not vacuous)."""
    gen = _load_generator()
    cel = gen.RelayCel()
    spec = {
        "label": "deliberate_divergence",
        "udf": "relay.coverage",
        # wasm-via-CEL returns true here; direct_args force a FALSE direct
        # result, so the cross-anchor MUST diverge and abort.
        "input_expression": 'relay.coverage({"steps": [{"name": "a"}]}, "a")',
        "bindings_py": {},
        "direct_args": [{"steps": [{"name": "a"}]}, "DELIBERATELY_WRONG"],
    }
    with pytest.raises(gen.CrossAnchorDivergence) as exc:
        gen.build_case(cel, spec)
    assert exc.value.label == "deliberate_divergence"
    assert exc.value.wasm_value != exc.value.direct_value


