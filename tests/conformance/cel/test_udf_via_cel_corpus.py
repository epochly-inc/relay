"""WS-E UDF-via-CEL corpus guard tests (M3 P3CORPUS).

These guards lock the four primaryFulfills assertions for the
``p3corpus-udf-via-cel-corpus-generator`` feature:

  VAL-CWC-P3CORPUS-001 (engines_fence / corpus_shape):
    A NEW corpus ``relay_udf_via_cel_corpus.json`` exists, SEPARATE from
    ``relay_cel_corpus.json``, and is the ONLY file these runners read. Every
    case carries ``engines == ["wasm"]`` (the structural fence excluding
    cel-js). The validating loader REJECTS any case whose ``engines`` is
    missing or not exactly ``["wasm"]``.

  VAL-CWC-P3CORPUS-002 (cel_js_parseable):
    Every case carries a boolean ``cel_js_parseable`` COMPUTED from the
    documented >=2-key map-literal-with-"type" boundary. This guard
    INDEPENDENTLY recomputes the flag (via the SHARED
    ``compute_cel_js_parseable`` the generator also uses) and asserts it
    matches the stored value for every case.

  VAL-CWC-P3CORPUS-003 (golden determinism + cel-python cross-anchor):
    Each case's stored golden equals a FRESH wasm eval (determinism) AND
    equals the cel-python DIRECT-call result serialized to typed-canonical
    (the cross-anchor that replaces the retired two-engine test_w17_4
    comparison).

  VAL-CWC-P3CORPUS-004 (udf_coverage / allowlist):
    All three Relay UDFs are exercised THROUGH CEL with at least one >=2-key
    map-literal boundary case (cel_js_parseable=false) per UDF, and no case
    references any UDF outside the three-name allowlist.

The corpus is generated by ``scripts/generate-relay-udf-via-cel-corpus.py``
from the BUILT wasm
(``packages/cel-wasm/crate/target/wasm32-unknown-unknown/release/relay_cel_wasm.wasm``
or ``$CEL_WASM``). All tests are tier-1 plumbing.

ASCII-only per CLAUDE.md "ASCII-Safe Source".
"""

from __future__ import annotations

import base64
import importlib.util
import json
import sys
from pathlib import Path
from typing import Any

import pytest

# Repo root: this file lives at relay/tests/conformance/cel/test_*.py
REPO_ROOT = Path(__file__).resolve().parents[3]
CORPUS_PATH = REPO_ROOT / "tests" / "conformance" / "cel" / "relay_udf_via_cel_corpus.json"
GENERATOR_PATH = REPO_ROOT / "scripts" / "generate-relay-udf-via-cel-corpus.py"
LEGACY_CORPUS_PATH = REPO_ROOT / "tests" / "conformance" / "cel" / "relay_cel_corpus.json"

# The 3-name UDF allowlist.
UDF_ALLOWLIST: frozenset[str] = frozenset(
    {"relay.coverage", "relay.tool_arg", "relay.schema_match"}
)

# Make the cel-python direct callables + py_to_typed + JCS encoder importable
# for the cross-anchor, and the wasm loader importable for the determinism
# check.
sys.path.insert(0, str(REPO_ROOT / "packages" / "contracts" / "src"))
sys.path.insert(0, str(REPO_ROOT / "packages" / "cel-wasm" / "python"))


def _load_generator() -> Any:
    """Load the hyphenated generator script as a module (a plain import cannot
    resolve a hyphenated filename)."""
    spec = importlib.util.spec_from_file_location(
        "relay_udf_via_cel_corpus_generator_under_test", GENERATOR_PATH
    )
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    sys.modules["relay_udf_via_cel_corpus_generator_under_test"] = mod
    spec.loader.exec_module(mod)
    return mod


def _load_corpus() -> dict[str, Any]:
    assert CORPUS_PATH.exists(), (
        f"VAL-CWC-P3CORPUS-001: missing UDF-via-CEL corpus at {CORPUS_PATH}; "
        "regenerate via `uv run python scripts/generate-relay-udf-via-cel-corpus.py`."
    )
    data = json.loads(CORPUS_PATH.read_text(encoding="utf-8"))
    assert isinstance(data, dict), "corpus root must be a JSON object"
    return data


def _cases() -> list[dict[str, Any]]:
    cases = _load_corpus().get("cases")
    assert isinstance(cases, list) and cases, "corpus must carry a non-empty 'cases' list"
    return cases


