@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-002")
def test_cel_js_parseable_present_and_boolean() -> None:
    for case in _cases():
        assert isinstance(case.get("cel_js_parseable"), bool), (
            f"VAL-CWC-P3CORPUS-002: case {case.get('label')!r} missing boolean "
            "cel_js_parseable"
        )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-002")
def test_cel_js_parseable_recomputed_matches_stored() -> None:
    """Independently recompute the boundary flag from input_expression (via the
    SHARED classifier the generator also uses) and assert it matches stored."""
    gen = _load_generator()
    mismatches: list[str] = []
    for case in _cases():
        expr = case["input_expression"]
        recomputed = gen.compute_cel_js_parseable(expr)
        stored = case["cel_js_parseable"]
        if recomputed != stored:
            mismatches.append(
                f"{case.get('label')!r}: stored={stored} recomputed={recomputed} "
                f"expr={expr!r}"
            )
    assert mismatches == [], (
        "VAL-CWC-P3CORPUS-002: cel_js_parseable mismatch:\n  " + "\n  ".join(mismatches)
    )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-CWC-P3CORPUS-002")
def test_cel_js_parseable_classifier_boundary_semantics() -> None:
    """The shared classifier implements the documented boundary precisely:
    a map literal with >=2 keys INCLUDING a "type" key -> False; otherwise True.
    """
    gen = _load_generator()
    f = gen.compute_cel_js_parseable
    # True cases (parseable):
    assert f('relay.coverage(trace, "x")') is True
    assert f('relay.schema_match(42, {"type": "integer"})') is True  # single key
    assert f('relay.tool_arg({"args": {"k": "v"}}, "k")') is True  # no "type" key
    assert f('relay.coverage({"steps": [{"name": "a"}]}, "a")') is True
    # False cases (NOT parseable by cel-js: >=2 keys incl. "type"):
    assert f('relay.schema_match({"a":1}, {"type": "object", "required": ["a"]})') is False
    assert f('relay.tool_arg({"type": "tc", "args": {"k": "v"}}, "k")') is False
    assert f('relay.coverage({"steps": [{"type": "t", "name": "a"}]}, "a")') is False
    # A brace inside a string literal is NOT a map literal (must not false-fire):
    assert f('relay.tool_arg(call, "a{type:b,c:d}")') is True


