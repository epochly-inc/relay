# ---------------------------------------------------------------------------
# Per-vector diff formatter (VAL-W17-022)
# ---------------------------------------------------------------------------


def _format_diff(
    case_name: str,
    case_category: str,
    expected_bytes: bytes,
    actual_bytes: bytes,
) -> str:
    """Format a per-vector full diff suitable for the pytest failure
    summary. Mandated by VAL-W17-022: any byte mismatch MUST be
    reported with the full expected vs actual bytes (hex), the
    decoded UTF-8 strings (with non-printable chars escaped), and
    the per-byte index of the first diverging byte. No count-only
    summary is acceptable.
    """
    min_len = min(len(expected_bytes), len(actual_bytes))
    first_diff_idx = -1
    for i in range(min_len):
        if expected_bytes[i] != actual_bytes[i]:
            first_diff_idx = i
            break
    if first_diff_idx == -1 and len(expected_bytes) != len(actual_bytes):
        first_diff_idx = min_len
    lines = [
        "VAL-W17-022 per-vector diff:",
        f"  case_name      = {case_name!r}",
        f"  category       = {case_category!r}",
        f"  expected_bytes = {expected_bytes!r}",
        f"  actual_bytes   = {actual_bytes!r}",
        f"  expected_hex   = {expected_bytes.hex()}",
        f"  actual_hex     = {actual_bytes.hex()}",
        f"  expected_len   = {len(expected_bytes)}",
        f"  actual_len     = {len(actual_bytes)}",
        f"  first_diff_idx = {first_diff_idx}",
    ]
    if first_diff_idx >= 0:
        e = expected_bytes[first_diff_idx] if first_diff_idx < len(expected_bytes) else None
        a = actual_bytes[first_diff_idx] if first_diff_idx < len(actual_bytes) else None
        lines.append(
            f"  first_diff_exp_byte = {e!r} actual_byte = {a!r}"
        )
    return "\n".join(lines)


