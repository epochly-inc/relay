# Generator drift guard -- catches a hand-edit to the corpus
# ---------------------------------------------------------------------------


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-W17-001")
def test_corpus_case_names_unique() -> None:
    corpus = _load_corpus()
    seen: set[str] = set()
    for case in corpus["cases"]:
        name = case["name"]
        assert name not in seen, f"duplicate case name in corpus: {name}"
        seen.add(name)
