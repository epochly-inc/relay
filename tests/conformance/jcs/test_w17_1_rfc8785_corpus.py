"""W17.1 RFC 8785 IETF conformance corpus tests.

Pinned-vector conformance suite that exercises the Python verifier's
JCS encoder against the IETF datatracker text of RFC 8785. The corpus
file ``tests/conformance/jcs/rfc8785_ietf_corpus.json`` and the
upstream-pins file ``tests/conformance/jcs/.upstream-pins.json`` are
generated by ``scripts/generate-jcs-rfc8785-ietf-corpus.py``. The
sibling vitest mirror at
``packages/verifier-typescript/test/w17_1_ietf_corpus.test.ts`` loads
the same files and asserts byte-identical output from the TS encoder
(VAL-W17-002 cross-runtime parity).

Assertion coverage:

  * VAL-W17-001: corpus sourced from IETF datatracker, pinned by SHA-256
    (asserted by ``test_corpus_pinned_to_ietf_datatracker``).
  * VAL-W17-002: 100% pass on cel-python JCS AND TS SDK JCS paths
    (Python half asserted here; TS half asserted in the vitest mirror).
  * VAL-W17-003: UTF-8 NFC normalization enforced before hashing
    (asserted by the NFC vector group + an explicit
    ``test_nfc_normalization_enforced`` check).
  * VAL-W17-004: number-serialization edge cases pass (RFC 8785 sec
    3.2.2.3) (asserted by the num_edge vector group + boundary checks).
  * VAL-W17-005: object-key sort order is RFC 8785 sec 3.2.3
    (asserted by the sort_utf16 vector group + adjacency checks).
  * VAL-W17-022: failures emit per-vector full diff (asserted by the
    ``_format_diff`` helper invoked on any mismatch).

ASCII-only per CLAUDE.md "ASCII-Safe Source".
"""

