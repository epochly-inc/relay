# VAL-W17-002: 100% pass on cel-python JCS path (Python half)
# ---------------------------------------------------------------------------


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-W17-002")
def test_every_vector_canonicalizes_byte_for_byte_python() -> None:
    """Every value-kind case canonicalizes to the corpus-pinned bytes
    via the verifier's JCS encoder. ANY single failure fails the
    suite. Per VAL-W17-022, the per-vector diff is emitted on
    failure (no count-only summary)."""
    corpus = _load_corpus()
    failures: list[str] = []
    pass_count = 0
    for case in corpus["cases"]:
        if case.get("kind") != "value":
            continue
        actual = jcs_canonicalize(case["input"])
        expected = base64.b64decode(case["expected_canonical_b64"])
        if actual != expected:
            failures.append(
                _format_diff(case["name"], case.get("category", ""), expected, actual)
            )
            continue
        # Defence in depth: the corpus's UTF-8 string mirror MUST
        # match the bytes when re-encoded.
        utf8_mirror = case["expected_canonical_utf8"].encode("utf-8")
        if actual != utf8_mirror:
            failures.append(
                _format_diff(
                    case["name"] + " (utf8 mirror)",
                    case.get("category", ""),
                    utf8_mirror,
                    actual,
                )
            )
            continue
        pass_count += 1
    assert not failures, (
        f"VAL-W17-002: {len(failures)} vector(s) failed Python parity:\n\n"
        + "\n\n".join(failures)
    )
    # Aggregate explicit count assertion for evidence-bundle pairing.
    expected_total = sum(1 for c in corpus["cases"] if c.get("kind") == "value")
    assert pass_count == expected_total, (
        f"VAL-W17-002: python_pass={pass_count} expected_total={expected_total}"
    )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-W17-002")
def test_corpus_sha256_digests_match_python_runtime() -> None:
    """The SHA-256 over the canonical bytes equals the corpus golden
    digest for every case. Drift across Python 3.12 / 3.13 / 3.14 of
    repr(float) byte form would fail here."""
    corpus = _load_corpus()
    failures: list[str] = []
    for case in corpus["cases"]:
        if case.get("kind") != "value":
            continue
        actual_digest = hashlib.sha256(jcs_canonicalize(case["input"])).hexdigest()
        if actual_digest != case["expected_sha256"]:
            failures.append(
                f"{case['name']}: expected={case['expected_sha256']!r} "
                f"actual={actual_digest!r}"
            )
    assert not failures, (
        f"VAL-W17-002: SHA-256 drift on {len(failures)} case(s):\n  "
        + "\n  ".join(failures)
    )


@pytest.mark.plumbing
@pytest.mark.fulfills("VAL-W17-002")
def test_every_sha256_digest_is_lowercase_hex_64() -> None:
    """Each corpus case's expected_sha256 is lowercase 64-char hex --
    catches a regenerator that emitted uppercase or short hex."""
    corpus = _load_corpus()
